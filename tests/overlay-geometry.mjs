import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';
import ts from 'typescript';

const source = await readFile(new URL('../src/overlayGeometry.ts', import.meta.url), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } }).outputText;
const module = { exports: {} };
vm.runInNewContext(compiled, { exports: module.exports, Number, Math });
const { alignedOverlay, duplicatedOverlay, normalizedOverlay, overlayStep, POINTS_PER_MM, resizeOverlay, rotatedOverlay90, translatedOverlay } = module.exports;
const near = (actual, expected) => assert.ok(Math.abs(actual - expected) < 1e-10, `${actual} != ${expected}`);
const plain = value => JSON.parse(JSON.stringify(value));
const pageWidth = 210 * POINTS_PER_MM, pageHeight = 297 * POINTS_PER_MM;
const original = { id: 'a', assetId: 'reuse', x: .2, y: .3, width: .15, height: .08, opacity: .7, blendMode: 'multiply', rotation: 0, locked: true };
const saved = JSON.stringify(original);
const quarter = rotatedOverlay90(original, pageWidth, pageHeight);
near(quarter.width * pageWidth, original.height * pageHeight);
near(quarter.height * pageHeight, original.width * pageWidth);
near(quarter.x + quarter.width / 2, original.x + original.width / 2);
near(quarter.y + quarter.height / 2, original.y + original.height / 2);
assert.equal(quarter.rotation, 90); assert.equal(quarter.blendMode, 'multiply'); assert.equal(quarter.locked, true);
let roundTrip = original;
for (let i = 0; i < 4; i++) roundTrip = rotatedOverlay90(roundTrip, pageWidth, pageHeight);
for (const key of ['x', 'y', 'width', 'height']) near(roundTrip[key], original[key]);
assert.equal(roundTrip.rotation, 0);
const tall = rotatedOverlay90({ ...original, x: 0, y: 0, width: .8, height: 1 }, pageWidth, pageHeight);
assert.ok(tall.width <= 1 && tall.height <= 1 && tall.x >= 0 && tall.y >= 0);
near(tall.width * pageWidth / (tall.height * pageHeight), pageHeight / (.8 * pageWidth));
const proportional = resizeOverlay({ ...original, locked: false }, 'width', .9, true);
near(proportional.width / proportional.height, original.width / original.height);
assert.ok(proportional.x + proportional.width <= 1 && proportional.y + proportional.height <= 1);
const free = resizeOverlay(original, 'width', .2, false);
near(free.width, .2); near(free.height, original.height);
for (const [alignment, axis, expected] of [['left', 'x', 0], ['right', 'x', 1 - original.width], ['centerX', 'x', (1 - original.width) / 2], ['top', 'y', 0], ['bottom', 'y', 1 - original.height], ['centerY', 'y', (1 - original.height) / 2]]) near(alignedOverlay(original, alignment)[axis], expected);
const copy = duplicatedOverlay(original, 'b', pageWidth, pageHeight);
assert.equal(copy.id, 'b'); assert.equal(copy.assetId, original.assetId); assert.equal(copy.locked, false);
near((copy.x - original.x) * pageWidth / POINTS_PER_MM, 3);
near((copy.y - original.y) * pageHeight / POINTS_PER_MM, 3);
near(overlayStep(pageWidth, false) * pageWidth / POINTS_PER_MM, .1);
near(overlayStep(pageHeight, true) * pageHeight / POINTS_PER_MM, 1);
const edge = translatedOverlay({ ...original, x: .99, y: .99 }, 1, 1);
near(edge.x + edge.width, 1); near(edge.y + edge.height, 1);
const invalid = normalizedOverlay({ ...original, x: NaN, y: Infinity, width: -1, height: NaN });
assert.ok([invalid.x, invalid.y, invalid.width, invalid.height].every(Number.isFinite));
assert.ok(invalid.width > 0 && invalid.height > 0);
assert.deepEqual(plain(rotatedOverlay90(original, 0, pageHeight)), plain(original));
assert.equal(JSON.stringify(original), saved, 'All geometry operations must leave the original snapshot unchanged');
console.log('PASS: physical millimeter geometry, proportional/free resize, page alignment, quarter turns, center/bounds, asset reuse and immutable copies');
